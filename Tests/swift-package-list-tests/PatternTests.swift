import Testing

@testable import swift_package_list

struct PatternTests {
    @Test(arguments: [
        ("", ""),
        ("abc", "abc"),
        ("a.b", "a.b"),
        (" abc ", " abc "),
        ("a\nb", "a\nb"),
        ("café", "café"),
        ("👩🏽‍💻", "👩🏽‍💻"),
        ("*", ""),
        ("*", "abc"),
        ("*", ".hidden"),
        ("a*", "abc"),
        ("abc*", "abc"),
        ("*c", "abc"),
        ("*abc", "abc"),
        ("a*c", "ac"),
        ("a*c", "abbc"),
        ("*b*", "abc"),
        ("**", ""),
        ("a**c", "abc"),
        ("a*b*c", "axbyc"),
        ("*ab*bc*", "abbc"),
        ("*aab", "aaab"),
        ("*ab*cd", "abxcdxcd"),
        ("a*b", "a\nb"),
        ("*界", "🌍世界"),
        ("?", "a"),
        ("?", "."),
        ("?", "\n"),
        ("a?c", "abc"),
        ("a??d", "abcd"),
        ("a?*c", "abc"),
        ("[abc]", "b"),
        ("[a-z]", "m"),
        ("[0-9]", "5"),
        ("[!abc]", "d"),
        ("[!a-z]", "5"),
        ("[[:digit:]]", "5"),
        ("[[:alpha:]]", "a"),
        ("[[:space:]]", "\t"),
        ("[]a]", "]"),
        ("[-a]", "-"),
        ("[a-]", "-"),
        ("[.]hidden", ".hidden"),
        ("file[0-9]?.*", "file1a.txt"),
        (#"a\*b"#, "a*b"),
        (#"a\?b"#, "a?b"),
        (#"\[abc\]"#, "[abc]"),
        (#"a\\b"#, #"a\b"#),
        (#"\a"#, "a"),
        ("/", "/"),
        ("a/b", "a/b"),
        ("a/*", "a/"),
        ("a/*", "a/b"),
        ("a/*", "a/.hidden"),
        ("a/?", "a/b"),
        ("a/[bc]", "a/b"),
        ("a/*/c", "a/b/c"),
        ("a/*/c", "a//c"),
        ("/*/c", "/b/c"),
        (#"a\/b"#, "a/b"),
        ("*", "/"),
        ("*", "a/b"),
        ("**", "a/b"),
        ("a*b", "a/b"),
        ("a?b", "a/b"),
        ("a[/]b", "a/b"),
        ("a[!x]b", "a/b"),
        ("a/*", "a/b/c"),
        ("a/**", "a/b/c"),
        ("a/*/c", "a/b/d/c"),
    ])
    func matches(pattern: String, value: String) {
        #expect(SwiftPackageList.Pattern(rawValue: pattern).matches(value))
    }

    @Test(arguments: [
        ("", "abc"),
        ("abc", ""),
        ("abd", "abc"),
        ("abc", "ab"),
        ("abc", "abcd"),
        ("abc", "xabc"),
        ("abc", "ABC"),
        ("abc", " abc "),
        ("a.b", "axb"),
        ("*🌍", "hello🌎"),
        ("a*", ""),
        ("a*c", "ab"),
        ("a*c", "abcd"),
        ("a*c", "xabc"),
        ("*d*", "abc"),
        ("*abc*", "ab"),
        ("a*b*c", "acb"),
        ("*ab*bc*", "abc"),
        ("a*a", "a"),
        ("*ab*cd", "abxcdxce"),
        ("?", ""),
        ("?", "ab"),
        ("a?c", "ac"),
        ("a?c", "abbc"),
        ("a??d", "abd"),
        ("a?*c", "ac"),
        ("[abc]", ""),
        ("[abc]", "d"),
        ("[abc]", "ab"),
        ("[a-z]", "A"),
        ("[0-9]", "a"),
        ("[!abc]", "a"),
        ("[!a-z]", "m"),
        ("[[:digit:]]", "a"),
        ("[[:alpha:]]", "5"),
        ("[[:space:]]", "a"),
        ("[]a]", "b"),
        ("[-a]", "b"),
        ("[a-]", "b"),
        ("[", "["),
        ("[abc", "[abc"),
        ("[abc", "a"),
        (#"a\*b"#, "axxb"),
        (#"a\?b"#, "acb"),
        (#"\[abc\]"#, "a"),
        (#"a\\b"#, "ab"),
        ("{a,b}", "a"),
        ("(a|b)", "a"),
        ("a/**/c", "a/c"),
        ("a/b", "a/b/"),
        ("a/b", "a/b/c"),
        ("a/b", "/a/b"),
    ]) func doesNotMatch(pattern: String, value: String) {
        #expect(!SwiftPackageList.Pattern(rawValue: pattern).matches(value))
    }
}
